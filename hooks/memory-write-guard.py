#!/usr/bin/env python3

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _lib.audit_log import record as _audit  # noqa: E402
from _lib.bypass import is_bypassed  # noqa: E402
from _lib.edit_resolution import resolved_change  # noqa: E402
from _lib.hook_input import read_hook_payload  # noqa: E402

HOOK = "memory-write-guard"
INDEX_NAME = "MEMORY.md"
GENERATED_BLOCK = re.compile(
    r"^(?:Everything below this line is generated|## Compiled from the vault"
    r"|.*This file is generated by the memory compile)",
    re.MULTILINE,
)
REQUIRED_PATH_PARTS = (".claude", "projects")
MEMORY_DIR_LEAF = "memory"
WATCHED_TOOLS = {"Write", "Edit", "MultiEdit"}


def _vault_configured() -> bool:
    raw = os.environ.get("SECOND_BRAIN_VAULT", "").strip()
    if not raw:
        return False
    try:
        return Path(raw).expanduser().is_dir()
    except OSError:
        return False


def _is_memory_path(path: str) -> bool:
    if not path:
        return False
    try:
        parts = Path(path).expanduser().parts
    except (OSError, ValueError):
        return False
    if MEMORY_DIR_LEAF not in parts:
        return False
    return all(part in parts for part in REQUIRED_PATH_PARTS)


def _generated_region(text: str) -> str:
    match = GENERATED_BLOCK.search(text)
    return text[match.start() :] if match else ""


def _keeps_generated_index(tool: str, tool_input: dict) -> bool:
    change = resolved_change(tool, tool_input)
    if change is None:
        return False
    return _generated_region(change.before) == _generated_region(change.after)


def main() -> int:
    if os.environ.get("MEMORY_WRITE_GUARD_DISABLE") == "1" or is_bypassed(HOOK):
        return 0
    if not _vault_configured():
        return 0

    event = read_hook_payload(HOOK)

    if event.get("tool_name") not in WATCHED_TOOLS:
        return 0

    tool_input = event.get("tool_input")
    if not isinstance(tool_input, dict):
        return 0

    file_path = tool_input.get("file_path", "")
    if not isinstance(file_path, str) or not _is_memory_path(file_path):
        return 0
    tool = str(event.get("tool_name"))
    if Path(file_path).name == INDEX_NAME and _keeps_generated_index(tool, tool_input):
        return 0
    _audit(hook=HOOK, decision="block", tool=tool, file_path=file_path)

    sys.stderr.write(
        "BLOCKED: the memory directory is generated from the vault, not written "
        "by hand.\n\n"
        f"  {file_path}\n\n"
        "A hand written memory file records neither when the fact was learned "
        "nor where it came from, and it escapes the compile's token budget.\n\n"
        "Instead:\n"
        "  1. Capture the fact as a vault note carrying `memory: true` and a\n"
        "     `memory-scope` of user, feedback, project, or reference.\n"
        "  2. Run `/brain compile` to regenerate this directory.\n\n"
        'Rule: CLAUDE.md "Knowledge Single Source of Truth", '
        "rules/knowledge-notes.md\n"
        "Bypass when migrating a pre-existing file: "
        "export MEMORY_WRITE_GUARD_DISABLE=1\n"
    )
    return 2


if __name__ == "__main__":
    sys.exit(main())
