def test_disable_env_bypasses(tool_use, run_hook):
    # Arrange
    payload = tool_use(
        "Bash",
        {"command": "git commit -m 'fix\n\nCo-authored-by: Claude'"},
    )

    # Act
    result = run_hook(HOOK, payload, env={"AI_ATTRIBUTION_DISABLE": "1"})

    # Assert
    assert_allowed(result)


def test_disable_env_other_value_does_not_bypass(tool_use, run_hook):
    # Arrange
    payload = tool_use(
        "Bash",
        {"command": "git commit -m 'fix\n\nCo-authored-by: Claude'"},
    )

    # Act
    result = run_hook(HOOK, payload, env={"AI_ATTRIBUTION_DISABLE": "0"})

    # Assert
    assert_blocked(result, "AI attribution detected")


