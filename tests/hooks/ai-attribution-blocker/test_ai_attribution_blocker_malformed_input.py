from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

from _helpers.hook_assertions import assert_allowed, assert_blocked

HOOK = "ai-attribution-blocker"


def test_write_non_string_content_blocks(tool_use, run_hook):
    # Arrange
    payload = tool_use(
        "Write",
        {"file_path": "/repo/src/x.ts", "content": 42},
    )

    # Act
    result = run_hook(HOOK, payload)

    # Assert
    assert_blocked(
        result,
        "Blocked: ai-attribution-blocker could not read its input: tool_input.content is not a",
    )


