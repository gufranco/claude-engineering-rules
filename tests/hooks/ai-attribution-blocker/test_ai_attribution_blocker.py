from __future__ import annotations


import pytest
from _helpers.hook_assertions import assert_blocked

HOOK = "ai-attribution-blocker"


@pytest.mark.parametrize(
    "line",
    [
        "Co-authored-by: Claude <noreply@anthropic.com>",
        "Co-authored-by: someone Anthropic AI",
        "co-authored-by: GPT bot",
        "Co-Authored-By: Copilot",
        "Co-authored-by: Cursor IDE",
    ],
)
def test_blocks_coauthored_by_ai(tool_use, run_hook, line):
    # Arrange
    payload = tool_use(
        "Bash",
        {"command": f"git commit -m 'fix: handle null\n\n{line}'"},
    )

    # Act
    result = run_hook(HOOK, payload)

    # Assert
    assert_blocked(result, "AI attribution detected")


