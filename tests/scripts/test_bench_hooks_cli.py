from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

from _helpers.bench_hooks_support import (
    SCRIPTS_DIR,
    TABLE_HEADER,
    TABLE_RULE,
    _allow_hook,
    _write_hook,
    bench_hooks,
)


DEFAULT_PAYLOAD_COUNT = 3


def test_cli_table_format_writes_to_stdout(
    hooks_dir: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # Arrange
    _write_hook(hooks_dir, "ok", _allow_hook())

    # Act
    rc = bench_hooks._cli(
        [
            "--hooks-dir",
            str(hooks_dir),
            "--iterations",
            "1",
            "--warmup",
            "0",
        ]
    )

    # Assert
    lines = capsys.readouterr().out.splitlines()
    assert rc == 0
    assert lines[:2] == [TABLE_HEADER, TABLE_RULE]
    assert lines[2].split()[:2] == ["ok", str(DEFAULT_PAYLOAD_COUNT)]
    assert len(lines) == 3


