def _json_cli_command(script: Path, hooks_dir: Path) -> list[str]:
    return [
        sys.executable,
        str(script),
        "--hooks-dir",
        str(hooks_dir),
        "--iterations",
        "1",
        "--warmup",
        "0",
        "--format",
        "json",
    ]


def test_main_module_runs_via_subprocess(
    hooks_dir: Path,
) -> None:
    # Arrange
    _write_hook(hooks_dir, "ok", _allow_hook())
    script = SCRIPTS_DIR / "_lib" / "bench_hooks.py"

    # Act
    proc = subprocess.run(
        _json_cli_command(script, hooks_dir),
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )

    # Assert
    assert proc.returncode == 0
    parsed = json.loads(proc.stdout)
    assert [(item["hook"], item["n"]) for item in parsed] == [
        ("ok", DEFAULT_PAYLOAD_COUNT)
    ]
